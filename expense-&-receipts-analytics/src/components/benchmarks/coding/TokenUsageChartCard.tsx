import React, { useMemo, useRef, useState } from "react";
import { Info, Minus, Plus, X } from "lucide-react";
import {
  ALL_CODING_AGENT_MODELS,
  DEFAULT_CODING_AGENT_MODEL_IDS,
  type CodingAgentModelItem,
} from "../data/codingAgentBenchmarks";
import { ModelsFilterControl } from "../ui/ChartCardControls";

const TOKEN_COLORS = {
  input: "#3B82F6",
  cachedInput: "#F59E0B",
  output: "#14B8A6",
};

const TOKEN_LEGEND = [
  { label: "Output", color: TOKEN_COLORS.output },
  { label: "Cached Input", color: TOKEN_COLORS.cachedInput },
  { label: "Input", color: TOKEN_COLORS.input },
];

const MAX_TOTAL_TOKENS_M = 30;

const formatM = (value: number): string => {
  const rounded = Math.round(value * 10) / 10;
  return `${Number.isInteger(rounded) ? rounded : rounded.toFixed(1)}M`;
};

const tokenTotal = (model: CodingAgentModelItem): number =>
  (model.inputTokens ?? 0) +
  (model.cachedInputTokens ?? 0) +
  (model.outputTokens ?? 0);

const segmentsFor = (model: CodingAgentModelItem) => [
  { color: TOKEN_COLORS.input, value: model.inputTokens ?? 0 },
  { color: TOKEN_COLORS.cachedInput, value: model.cachedInputTokens ?? 0 },
  { color: TOKEN_COLORS.output, value: model.outputTokens ?? 0 },
];

const TOKEN_NOTES: { id: string; title: string; body: string }[] = [
  {
    id: "input",
    title: "Input Tokens",
    body: "Non-cached input tokens sent to the model, including prompts, instructions, tool context, and task context that were not served from prompt cache.",
  },
  {
    id: "cached-input",
    title: "Cached Input Tokens",
    body: "Input tokens served from the provider's prompt cache, billed at a reduced rate and counted separately from non-cached input.",
  },
  {
    id: "why-cache",
    title: "Why Cache Usage Varies",
    body: "Cache hit rates depend on provider routing, request timing, and how much of the prompt is reused across tasks, so cached token counts vary between agents.",
  },
  {
    id: "output",
    title: "Output Tokens",
    body: "Tokens generated by the model, including reasoning, tool calls, and final responses that were not served from prompt cache.",
  },
];

const MORE_TOKEN_NOTES: { id: string; title: string; body: string }[] = [
  {
    id: "total",
    title: "Total Tokens",
    body: "The sum of non-cached input, cached input, and output tokens consumed per task.",
  },
  {
    id: "efficiency",
    title: "Token Efficiency",
    body: "Fewer tokens per task generally indicates a more efficient agent, though task difficulty and verification retries can increase usage.",
  },
  {
    id: "routing",
    title: "Cache Routing",
    body: "Providers route requests differently, which changes how much of a repeated prompt is served from cache across runs.",
  },
];

// ── Chart geometry ──
const SVG_HEIGHT = 265;
const BASELINE_Y = 175;
const MAX_BAR_HEIGHT = 145;
const GRIDLINE_VALUES = [5, 10, 15, 20, 25];

export const TokenUsageChartCard: React.FC = () => {
  const [selectedModelIds, setSelectedModelIds] = useState<string[]>(() => [
    ...DEFAULT_CODING_AGENT_MODEL_IDS,
  ]);
  const [hoveredModel, setHoveredModel] = useState<CodingAgentModelItem | null>(
    null
  );
  const [tooltipPos, setTooltipPos] = useState<{ x: number; y: number } | null>(
    null
  );
  const [openNoteIds, setOpenNoteIds] = useState<string[]>([]);
  const [showMoreNotes, setShowMoreNotes] = useState(false);

  const containerRef = useRef<HTMLDivElement>(null);

  const chartModels = useMemo(
    () =>
      ALL_CODING_AGENT_MODELS.filter(
        (model) =>
          selectedModelIds.includes(model.id) && model.inputTokens !== undefined
      ).sort((a, b) => tokenTotal(b) - tokenTotal(a)),
    [selectedModelIds]
  );

  const toggleNote = (noteId: string) => {
    setOpenNoteIds((prev) =>
      prev.includes(noteId)
        ? prev.filter((id) => id !== noteId)
        : [...prev, noteId]
    );
  };

  const visibleNotes = showMoreNotes
    ? [...TOKEN_NOTES, ...MORE_TOKEN_NOTES]
    : TOKEN_NOTES;

  const SVG_TOTAL_WIDTH = Math.max(1140, chartModels.length * 76);
  const slotWidth = SVG_TOTAL_WIDTH / Math.max(1, chartModels.length);
  const barWidth = Math.min(46, Math.max(36, slotWidth - 28));

  return (
    <div className="w-full max-w-[1560px] mx-auto font-sans px-1">
      <div
        ref={containerRef}
        className="w-full bg-white rounded-2xl relative select-none shadow-xs border border-transparent"
      >
        {/* ── Tab bar ── */}
        <div className="flex items-center gap-1 px-6 sm:px-8 pt-4 pb-3 border-b border-transparent">
          <span className="px-3 py-1.5 rounded-md text-[13px] font-semibold bg-[#F1F3F5] text-neutral-900 select-none">
            Token Usage
          </span>
        </div>

        <div className="p-6 sm:p-8">
          {/* ── Title, Subtitle & Action Controls Row ── */}
          <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4 mb-2">
            <div className="flex flex-col max-w-2xl">
              <h3 className="font-serif text-[24px] sm:text-[26px] font-normal text-neutral-900 tracking-tight leading-tight">
                Token Usage per Task
              </h3>
              <p className="text-[12.5px] text-neutral-500 mt-1 leading-normal">
                Average input, cache, and output tokens per task
              </p>
            </div>

            <div className="flex flex-col items-end gap-2.5 shrink-0 self-start sm:self-auto">
              <ModelsFilterControl
                models={ALL_CODING_AGENT_MODELS}
                selectedIds={selectedModelIds}
                onChangeSelection={setSelectedModelIds}
                defaultIds={DEFAULT_CODING_AGENT_MODEL_IDS}
                swatchColorFor={(model) => model.modelColor}
                shownCount={chartModels.length}
              />
            </div>
          </div>

          {/* ── Legend + Watermark ── */}
          <div className="flex items-center justify-between w-full mb-2">
            <div className="flex items-center gap-4">
              {TOKEN_LEGEND.map((entry) => (
                <span
                  key={entry.label}
                  className="inline-flex items-center gap-1.5 text-[12px] text-neutral-600"
                >
                  <span
                    className="w-2.5 h-2.5 rounded-full"
                    style={{ backgroundColor: entry.color }}
                  />
                  {entry.label}
                </span>
              ))}
            </div>
          </div>

          {/* ── Chart ── */}
          {chartModels.length === 0 ? (
            <div className="flex items-center justify-center h-[265px]">
              <p className="text-[13px] text-neutral-500">No models selected.</p>
            </div>
          ) : (
            <div className="w-full overflow-x-auto no-scrollbar">
              <svg
                viewBox={`0 0 ${SVG_TOTAL_WIDTH} ${SVG_HEIGHT}`}
                className="w-full h-auto overflow-visible select-none"
                style={{ minWidth: `${SVG_TOTAL_WIDTH}px`, maxHeight: "310px" }}
              >
                {/* Gridlines */}
                {GRIDLINE_VALUES.map((value) => {
                  const y =
                    BASELINE_Y - (value / MAX_TOTAL_TOKENS_M) * MAX_BAR_HEIGHT;
                  return (
                    <line
                      key={value}
                      x1={0}
                      x2={SVG_TOTAL_WIDTH}
                      y1={y}
                      y2={y}
                      stroke="#E5E7EB"
                      strokeWidth={1}
                      strokeDasharray="3 4"
                    />
                  );
                })}

                {chartModels.map((model, index) => {
                  const cx = index * slotWidth + slotWidth / 2;
                  const bx = cx - barWidth / 2;

                  const segments = segmentsFor(model).filter(
                    (segment) => segment.value > 0
                  );

                  const heightFor = (segment: { value: number }) =>
                    (segment.value / MAX_TOTAL_TOKENS_M) * MAX_BAR_HEIGHT;

                  const totalHeight = segments.reduce(
                    (sum, segment) => sum + heightFor(segment),
                    0
                  );
                  const topY = BASELINE_Y - totalHeight;

                  let cursor = BASELINE_Y;

                  return (
                    <g key={model.id}>
                      {/* Stacked segments (bottom → top) */}
                      {segments.map((segment, segmentIndex) => {
                        const height = heightFor(segment);
                        const y = cursor - height;
                        const isTop = segmentIndex === segments.length - 1;
                        cursor = y;
                        return (
                          <g key={segment.color}>
                            <rect
                              x={bx}
                              y={y}
                              width={barWidth}
                              height={height}
                              rx={isTop ? 2.5 : 0}
                              fill={segment.color}
                            />
                            {height >= 16 && (
                              <text
                                x={cx}
                                y={y + height / 2 + 4.5}
                                textAnchor="middle"
                                fill="#FFFFFF"
                                fontSize={12.5}
                                fontWeight={700}
                                className="select-none font-sans pointer-events-none"
                              >
                                {formatM(segment.value)}
                              </text>
                            )}
                          </g>
                        );
                      })}

                      {/* Total label above bar */}
                      <text
                        x={cx}
                        y={topY - 8}
                        textAnchor="middle"
                        fill="#0F172A"
                        fontSize={11.5}
                        fontWeight={600}
                        className="select-none font-sans pointer-events-none"
                      >
                        {formatM(tokenTotal(model))}
                      </text>

                      {/* ── Labels below Baseline ── */}

                      {/* Line 1: Agent Name */}
                      <text
                        x={cx}
                        y={BASELINE_Y + 19}
                        textAnchor="middle"
                        fill="#0F172A"
                        fontSize={11.5}
                        fontWeight={600}
                        className="select-none font-sans pointer-events-none"
                      >
                        {model.agentName}
                      </text>

                      {/* Line 2: Model Name line 1 */}
                      <text
                        x={cx}
                        y={BASELINE_Y + 34}
                        textAnchor="middle"
                        fill="#334155"
                        fontSize={11}
                        fontWeight={500}
                        className="select-none font-sans pointer-events-none"
                      >
                        {model.modelLines[0] || ""}
                      </text>

                      {/* Line 3: Model Name line 2 */}
                      {model.modelLines[1] && (
                        <text
                          x={cx}
                          y={BASELINE_Y + 48}
                          textAnchor="middle"
                          fill="#64748B"
                          fontSize={10.5}
                          fontWeight={400}
                          className="select-none font-sans pointer-events-none"
                        >
                          {model.modelLines[1]}
                        </text>
                      )}

                      {/* Line 4: Model Name line 3 */}
                      {model.modelLines[2] && (
                        <text
                          x={cx}
                          y={BASELINE_Y + 62}
                          textAnchor="middle"
                          fill="#94A3B8"
                          fontSize={10}
                          fontWeight={400}
                          className="select-none font-sans pointer-events-none"
                        >
                          {model.modelLines[2]}
                        </text>
                      )}

                      {/* Provider */}
                      {model.providerDisplay && (
                        <text
                          x={cx}
                          y={BASELINE_Y + 34 + 14 * model.modelLines.length}
                          textAnchor="middle"
                          fill="#94A3B8"
                          fontSize={10}
                          fontWeight={400}
                          className="select-none font-sans pointer-events-none"
                        >
                          {model.providerDisplay}
                        </text>
                      )}

                      {/* Full column invisible hover hit area */}
                      <rect
                        x={index * slotWidth}
                        y={0}
                        width={slotWidth}
                        height={SVG_HEIGHT}
                        fill="transparent"
                        className="cursor-pointer"
                        onMouseEnter={(e) => {
                          const rect =
                            containerRef.current?.getBoundingClientRect();
                          const clientRect =
                            e.currentTarget.getBoundingClientRect();
                          if (rect) {
                            setTooltipPos({
                              x:
                                clientRect.left -
                                rect.left +
                                clientRect.width / 2,
                              y: clientRect.top - rect.top + topY,
                            });
                          }
                          setHoveredModel(model);
                        }}
                        onMouseLeave={() => {
                          setHoveredModel(null);
                          setTooltipPos(null);
                        }}
                      />
                    </g>
                  );
                })}
              </svg>

              {/* Interactive Tooltip Card */}
              {hoveredModel && tooltipPos && (
                <div
                  className="absolute z-50 bg-white border border-neutral-200/80 rounded-xl p-3.5 shadow-xl pointer-events-none transition-all duration-75 min-w-[240px]"
                  style={{
                    left: `${Math.min(
                      (containerRef.current?.clientWidth || 900) - 260,
                      Math.max(20, tooltipPos.x - 120)
                    )}px`,
                    top: `${Math.max(20, tooltipPos.y - 130)}px`,
                  }}
                >
                  <div className="flex items-center justify-between gap-2 border-b border-neutral-100 pb-1.5">
                    <span className="text-[13px] font-bold text-neutral-900 leading-snug">
                      {hoveredModel.agentName}
                    </span>
                    <span className="text-[11.5px] text-neutral-400 font-mono">
                      {hoveredModel.creatorName}
                    </span>
                  </div>

                  <div className="text-[12px] font-medium text-neutral-700 mt-1">
                    {hoveredModel.name}
                  </div>

                  <div className="flex flex-col gap-1.5 mt-2.5 text-[11.5px] pt-1.5 border-t border-neutral-100">
                    <div className="flex items-center justify-between">
                      <span className="text-neutral-500">Total Tokens:</span>
                      <span className="font-bold text-neutral-900 font-mono text-sm">
                        {formatM(tokenTotal(hoveredModel))}
                      </span>
                    </div>
                    <div className="flex items-center justify-between">
                      <span className="text-neutral-500">Input:</span>
                      <span className="font-semibold text-neutral-800 font-mono">
                        {formatM(hoveredModel.inputTokens ?? 0)}
                      </span>
                    </div>
                    <div className="flex items-center justify-between">
                      <span className="text-neutral-500">Cached Input:</span>
                      <span className="font-semibold text-neutral-800 font-mono">
                        {formatM(hoveredModel.cachedInputTokens ?? 0)}
                      </span>
                    </div>
                    <div className="flex items-center justify-between">
                      <span className="text-neutral-500">Output:</span>
                      <span className="font-semibold text-neutral-800 font-mono">
                        {formatM(hoveredModel.outputTokens ?? 0)}
                      </span>
                    </div>
                  </div>
                </div>
              )}
            </div>
          )}

          {/* ── Notes footer ── */}
          <div className="mt-6">
            <div className="flex items-start gap-2 py-3 text-[12.5px] text-neutral-500 leading-normal">
              <Info size={14} className="text-neutral-400 mt-0.5 shrink-0" />
              <span>
                Prompt cache hit rates can vary significantly by provider
                routing, which can materially change effective cost.
              </span>
            </div>

            {visibleNotes.map((note) => {
              const isOpen = openNoteIds.includes(note.id);
              return (
                <div key={note.id} className="border-t border-transparent">
                  <button
                    type="button"
                    onClick={() => toggleNote(note.id)}
                    className="flex items-center justify-between w-full py-3 cursor-pointer group"
                  >
                    <span className="flex items-center gap-2 text-[13px] font-medium text-neutral-700 group-hover:text-neutral-900 transition-colors">
                      <Info size={14} className="text-neutral-400" />
                      {note.title}
                    </span>
                    {isOpen ? (
                      <X size={15} className="text-neutral-400" />
                    ) : (
                      <Plus size={15} className="text-neutral-400" />
                    )}
                  </button>
                  {isOpen && (
                    <p className="text-[13px] text-neutral-800 leading-relaxed pb-3 -mt-1">
                      {note.body}
                    </p>
                  )}
                </div>
              );
            })}

            <button
              type="button"
              onClick={() => setShowMoreNotes((prev) => !prev)}
              className="flex items-center gap-1.5 py-3 text-[13px] font-medium text-neutral-600 hover:text-neutral-900 transition-colors cursor-pointer"
            >
              {showMoreNotes ? <Minus size={14} /> : <Plus size={14} />}
              3 more notes
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
